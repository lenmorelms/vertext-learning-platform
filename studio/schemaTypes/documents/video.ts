import { VideoIcon } from "@sanity/icons";
import { defineArrayMember, defineField, defineType } from "sanity";

/**
 * Built by `scripts/ingest-videos.ts`, one per unique lesson video. An internal
 * lookup for search, never shown to learners. Edit chapters in
 * `scripts/videos/chapters.json`, not here: a re-run replaces the document.
 */
export const video = defineType({
  name: "video",
  title: "Video",
  type: "document",
  icon: VideoIcon,
  readOnly: true,
  description: "Generated by the video ingestion pipeline. Read only.",
  fields: [
    defineField({ name: "title", description: "The provider's title.", type: "string" }),
    defineField({
      name: "provider",
      type: "string",
      options: { list: [{ title: "YouTube", value: "youtube" }] },
    }),
    defineField({ name: "videoId", title: "Video ID", description: "The provider's id.", type: "string" }),
    defineField({
      name: "url",
      title: "URL",
      description: "Canonical video URL. Lessons link to this document by matching their video URL.",
      type: "url",
    }),
    defineField({ name: "durationSeconds", title: "Duration (seconds)", type: "number" }),
    defineField({
      name: "chapters",
      description: "Table of contents.",
      type: "array",
      of: [
        defineArrayMember({
          name: "chapter",
          type: "object",
          fields: [
            defineField({ name: "startSeconds", type: "number" }),
            defineField({ name: "label", type: "string" }),
          ],
          preview: { select: { title: "label", subtitle: "startSeconds" } },
        }),
      ],
    }),
    defineField({
      name: "chunks",
      description: "The transcript in short timestamped pieces.",
      type: "array",
      of: [
        defineArrayMember({
          name: "chunk",
          type: "object",
          fields: [
            defineField({ name: "startSeconds", type: "number" }),
            defineField({ name: "text", type: "text", rows: 3 }),
          ],
          preview: { select: { title: "text", subtitle: "startSeconds" } },
        }),
      ],
    }),
    defineField({
      name: "chapterSource",
      description: "Where the chapters came from.",
      type: "string",
      options: {
        list: [
          { title: "Authored", value: "authored" },
          { title: "Description", value: "description" },
          { title: "None", value: "none" },
        ],
      },
    }),
    defineField({ name: "ingestedAt", type: "datetime" }),
  ],
  preview: {
    select: { title: "title", chapters: "chapters", chunks: "chunks" },
    prepare: ({ title, chapters, chunks }) => ({
      title,
      subtitle: `${chapters?.length ?? 0} chapters · ${chunks?.length ?? 0} chunks`,
    }),
  },
});
